// Command gen writes this module's generated source: an accessor for each
// service of the Toshi Workspace API, and this module's version taken from the
// version of the API it is built against.
//
// Run it with go generate ./...
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strings"

	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/reflect/protoregistry"

	"go.toshicloud.io/api"
	_ "go.toshicloud.io/api/workspacev1"
)

// apiPackage is the protobuf package that holds the Workspace API's services.
const apiPackage = "toshi.workspace.v1"

// header starts every generated file.
const header = "// Code generated by go run ./internal/gen. DO NOT EDIT.\n\n"

// wrapped holds the services whose client is wrapped by hand in client.go:
// WorkloadService, whose calls a job, a sandbox and a service each reach, and
// EndpointService, whose client is this package's own interface. Their
// accessors stay hand-written, so the generator leaves them out.
var wrapped = map[string]bool{
	"WorkloadService": true,
	"EndpointService": true,
}

func main() {
	if err := run(); err != nil {
		log.Fatal(err)
	}
}

// run writes every generated file.
func run() error {
	services := apiServices()
	if len(services) == 0 {
		return fmt.Errorf("internal/gen: the API defines no services")
	}
	if err := write("services_gen.go", servicesSource(services)); err != nil {
		return err
	}
	return write("version.go", versionSource(api.Version()))
}

// apiServices returns the API's services that the generator writes, in name
// order.
func apiServices() []protoreflect.ServiceDescriptor {
	var services []protoreflect.ServiceDescriptor
	protoregistry.GlobalFiles.RangeFiles(func(file protoreflect.FileDescriptor) bool {
		if string(file.Package()) != apiPackage {
			return true
		}
		descriptors := file.Services()
		for i := 0; i < descriptors.Len(); i++ {
			service := descriptors.Get(i)
			if wrapped[string(service.Name())] {
				continue
			}
			services = append(services, service)
		}
		return true
	})
	sort.Slice(services, func(i, j int) bool {
		return services[i].Name() < services[j].Name()
	})
	return services
}

// serviceName returns the Go name of a service's client, for example
// ProjectService.
func serviceName(service protoreflect.ServiceDescriptor) string {
	return string(service.Name())
}

// accessor returns the service's accessor, its name without the Service
// suffix, for example Project.
func accessor(service protoreflect.ServiceDescriptor) string {
	return strings.TrimSuffix(serviceName(service), "Service")
}

// field returns the field of services that holds the service's client, the
// accessor with a leading lower-case letter, for example project.
func field(service protoreflect.ServiceDescriptor) string {
	name := accessor(service)
	return strings.ToLower(name[:1]) + name[1:]
}

// servicesSource returns the source of services_gen.go.
func servicesSource(services []protoreflect.ServiceDescriptor) []byte {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package toshi\n\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"connectrpc.com/connect\"\n\n")
	b.WriteString("\tworkspacev1connect \"go.toshicloud.io/api/workspacev1/workspacev1connect\"\n")
	b.WriteString(")\n\n")
	b.WriteString("// services holds the client of every service of the Workspace API whose\n")
	b.WriteString("// accessor is generated. Client embeds it.\n")
	b.WriteString("type services struct {\n")
	for _, service := range services {
		fmt.Fprintf(&b, "\t%s workspacev1connect.%sClient\n", field(service), serviceName(service))
	}
	b.WriteString("}\n\n")
	b.WriteString("// newServices builds the client of every service from api, server and\n")
	b.WriteString("// options.\n")
	b.WriteString("func newServices(api connect.HTTPClient, server string, options ...connect.ClientOption) services {\n")
	b.WriteString("\treturn services{\n")
	for _, service := range services {
		fmt.Fprintf(&b, "\t\t%s: workspacev1connect.New%sClient(api, server, options...),\n",
			field(service), serviceName(service))
	}
	b.WriteString("\t}\n")
	b.WriteString("}\n")
	for _, service := range services {
		fmt.Fprintf(&b, "\n// %s is the %s client.\n", accessor(service), serviceName(service))
		fmt.Fprintf(&b, "func (c *Client) %s() workspacev1connect.%sClient { return c.%s }\n",
			accessor(service), serviceName(service), field(service))
	}
	return b.Bytes()
}

// versionSource returns the source of version.go.
func versionSource(version string) []byte {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("package toshi\n\n")
	b.WriteString("// Version is this module's version without the leading v: the version of the\n")
	b.WriteString("// Toshi API this module is built against, as the API module's VERSION file\n")
	b.WriteString("// holds it.\n")
	fmt.Fprintf(&b, "const Version = %q\n", version)
	return b.Bytes()
}

// write formats source and writes it to name.
func write(name string, source []byte) error {
	formatted, err := format.Source(source)
	if err != nil {
		return fmt.Errorf("internal/gen: format %s: %w", name, err)
	}
	if err := os.WriteFile(name, formatted, 0o644); err != nil {
		return fmt.Errorf("internal/gen: write %s: %w", name, err)
	}
	return nil
}
